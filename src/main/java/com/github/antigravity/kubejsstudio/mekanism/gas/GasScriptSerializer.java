package com.github.antigravity.kubejsstudio.mekanism.gas;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Serializes and parses KubeJS Mekanism Gas registration scripts.
 */
public final class GasScriptSerializer {
    private static final Pattern CREATE_PATTERN = Pattern.compile(
            "event\\.create\\(\\s*['\"]([^'\"]+)['\"]\\s*\\)",
            Pattern.MULTILINE
    );
    private static final Pattern DISPLAY_NAME_PATTERN = Pattern.compile("\\.displayName\\(\\s*['\"]([^'\"]+)['\"]\\s*\\)");
    private static final Pattern COLOR_PATTERN = Pattern.compile("\\.color\\(\\s*(?:0x|#)?([0-9a-fA-F]+)\\s*\\)");
    private static final Pattern TEXTURE_PATTERN = Pattern.compile("\\.texture\\(\\s*['\"]([^'\"]+)['\"]\\s*\\)");
    private static final Pattern RADIOACTIVITY_PATTERN = Pattern.compile("\\.radioactivity\\(\\s*([0-9.]+)\\s*\\)");
    private static final Pattern TAG_PATTERN = Pattern.compile("\\.tag\\(\\s*['\"]([^'\"]+)['\"]\\s*\\)");

    private GasScriptSerializer() {}

    /**
     * Builds a full KubeJS startup script containing all given gas definitions.
     */
    public static String buildStartupScript(Collection<MekanismGasDefinition> gases) {
        StringBuilder sb = new StringBuilder();
        sb.append("// Priority: 0\n");
        sb.append("// Mekanism Gas Registrations generated by KubeJS Studio\n\n");
        sb.append("StartupEvents.registry('mekanism:gas', event => {\n");
        for (MekanismGasDefinition gas : gases) {
            sb.append(gas.toKubeJsStatement()).append("\n\n");
        }
        sb.append("});\n");
        return sb.toString();
    }

    /**
     * Parses gas definitions from an existing KubeJS script string.
     */
    public static List<MekanismGasDefinition> parseScript(String scriptContent) {
        List<MekanismGasDefinition> list = new ArrayList<>();
        if (scriptContent == null || scriptContent.isBlank()) {
            return list;
        }

        Matcher matcher = CREATE_PATTERN.matcher(scriptContent);
        int lastEnd = 0;
        List<int[]> blockRanges = new ArrayList<>();

        while (matcher.find()) {
            blockRanges.add(new int[]{matcher.start(), matcher.end()});
        }

        for (int i = 0; i < blockRanges.size(); i++) {
            int start = blockRanges.get(i)[0];
            int nextStart = (i + 1 < blockRanges.size()) ? blockRanges.get(i + 1)[0] : scriptContent.length();
            String block = scriptContent.substring(start, nextStart);

            Matcher createMatcher = CREATE_PATTERN.matcher(block);
            if (createMatcher.find()) {
                String gasName = createMatcher.group(1);
                String id = gasName.contains(":") ? gasName : ("kubejs:" + gasName);
                MekanismGasDefinition.Builder builder = MekanismGasDefinition.builder(id);

                Matcher nameMatcher = DISPLAY_NAME_PATTERN.matcher(block);
                if (nameMatcher.find()) {
                    builder.displayName(nameMatcher.group(1));
                }

                Matcher colorMatcher = COLOR_PATTERN.matcher(block);
                if (colorMatcher.find()) {
                    try {
                        builder.color(Integer.parseInt(colorMatcher.group(1), 16));
                    } catch (NumberFormatException ignored) {}
                }

                Matcher texMatcher = TEXTURE_PATTERN.matcher(block);
                if (texMatcher.find()) {
                    builder.texture(texMatcher.group(1));
                }

                Matcher radMatcher = RADIOACTIVITY_PATTERN.matcher(block);
                if (radMatcher.find()) {
                    try {
                        builder.radioactivity(Double.parseDouble(radMatcher.group(1)));
                    } catch (NumberFormatException ignored) {}
                }

                Matcher tagMatcher = TAG_PATTERN.matcher(block);
                while (tagMatcher.find()) {
                    builder.tag(tagMatcher.group(1));
                }

                list.add(builder.build());
            }
        }

        return list;
    }
}
