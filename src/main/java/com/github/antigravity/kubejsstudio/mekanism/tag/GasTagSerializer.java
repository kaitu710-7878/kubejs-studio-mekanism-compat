package com.github.antigravity.kubejsstudio.mekanism.tag;

import java.util.Collection;
import java.util.List;

/**
 * Serializes Mekanism Gas Tag definitions into KubeJS script files or Datapack JSONs.
 */
public final class GasTagSerializer {
    private GasTagSerializer() {}

    /**
     * Builds a full KubeJS server script for Mekanism Gas tags.
     */
    public static String buildServerScript(Collection<MekanismGasTagDefinition> tags) {
        StringBuilder sb = new StringBuilder();
        sb.append("// Priority: 0\n");
        sb.append("// Mekanism Gas Tag modifications generated by KubeJS Studio\n\n");
        sb.append("ServerEvents.tags('").append(MekanismGasTagDefinition.REGISTRY).append("', event => {\n");
        for (MekanismGasTagDefinition tag : tags) {
            for (String statement : tag.toKubeJsStatements()) {
                sb.append(statement).append("\n");
            }
        }
        sb.append("});\n");
        return sb.toString();
    }
}
